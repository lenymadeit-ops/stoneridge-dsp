"""Fit a 4-harmonic cosine-Fourier potential to the acetanilide torsional PES,
derive the odd restoring torque f(x) = -dV/dtheta around 180 deg, and validate
smooth monotonicity and hysteresis ratio for Adaa2MolecularShaper.h.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
import numpy as np


def main() -> None:
    pes_path = Path(
        r"C:\Users\dell\.gemini\antigravity\brain\5d1b170b-c675-4762-bfce-ba4960c2d527\scratch\acetanilide_pes.json"
    )
    if not pes_path.exists():
        raise SystemExit(f"missing {pes_path}")

    pes = json.loads(pes_path.read_text(encoding="utf-8"))
    angles = np.asarray(pes["angles_deg"], dtype=np.float64)
    energy = np.asarray(pes["energy_envelope_kcal_mol"], dtype=np.float64)
    hyst = np.asarray(pes["hysteresis_kcal_mol"], dtype=np.float64)

    phi = np.radians(angles - 180.0)
    # 4-harmonic cosine-Fourier potential V(phi) = c0 + sum_{m=1..4} c_m cos(m * phi)
    design = np.column_stack([np.ones_like(phi)] + [np.cos(m * phi) for m in range(1, 5)])
    c, *_ = np.linalg.lstsq(design, energy, rcond=None)
    v_fit = design @ c
    v_rms = float(np.sqrt(np.mean((v_fit - energy) ** 2)))

    # Restoring torque at phi = -omega * x: f(x) = sum_{m=1..4} (-m * c_m) * sin(m * omega * x)
    a_raw = np.array([-float(m) * c[m] for m in range(1, 5)], dtype=np.float64)
    omega = 1.05
    xs = np.linspace(-1.25, 1.25, 2501)
    vals = sum(a_raw[m] * np.sin((m + 1) * omega * xs) for m in range(4))
    peak_val = float(np.max(np.abs(vals)))
    a_norm = a_raw / peak_val
    slope0 = float(omega * sum((m + 1) * a_norm[m] for m in range(4)))

    barrier = float(pes.get("barrier_kcal_mol", np.max(energy) - np.min(energy)))
    max_hyst = float(pes.get("max_hysteresis_kcal_mol", np.max(hyst)))
    hyst_ratio = max_hyst / max(barrier, 1e-6)

    print(f"V(phi) cosine-Fourier fit RMS = {v_rms:.4f} kcal/mol (barrier={barrier:.3f}, max_hyst={max_hyst:.4f})")
    print(f"a_norm (peak-scaled <= 1.0 over [-1.25,1.25]) = {[round(float(v), 6) for v in a_norm]}")
    print(f"omega={omega:.4f}, small_signal_slope={slope0:.4f}, hyst_ratio={hyst_ratio:.6f}")

    # Verify ADAA2 vs direct torque continuity & boundedness
    y_05 = sum(a_norm[m] * np.sin((m + 1) * omega * 0.5) for m in range(4))
    y_10 = sum(a_norm[m] * np.sin((m + 1) * omega * 1.0) for m in range(4))
    print(f"Sample curve: f(0.5)={y_05:.4f}, f(1.0)={y_10:.4f}, max|f|={float(np.max(np.abs(vals / peak_val))):.4f}")

    repo_root = Path(__file__).resolve().parents[3]
    out_hdr = repo_root / "src" / "vocal" / "Adaa2MolecularCoeffs.h"
    hdr = "\n".join([
        "#pragma once",
        "",
        "// Auto-generated by tools/lab/lab/fit_acetanilide_adaa2.py from acetanilide_pes.json.",
        f"// Cosine-Fourier V(theta) 4-harmonic fit RMS = {v_rms:.4f} kcal/mol, barrier = {barrier:.3f} kcal/mol.",
        "",
        "namespace stoneridge::vocal {",
        "",
        "struct MolecularTorqueCoeffs {",
        "    float a1;",
        "    float a2;",
        "    float a3;",
        "    float a4;",
        "    float omega;",
        "    float hyst;",
        "    float smallSignalGain;",
        "};",
        "",
        "inline constexpr MolecularTorqueCoeffs kAcetanilideTorque{",
        f"    {a_norm[0]:.7f}f, {a_norm[1]:.7f}f, {a_norm[2]:.7f}f, {a_norm[3]:.7f}f,",
        f"    {omega:.4f}f, {hyst_ratio:.6f}f, {slope0:.6f}f",
        "};",
        "",
        "} // namespace stoneridge::vocal",
        "",
    ])
    out_hdr.write_text(hdr, encoding="ascii")
    print(f"Wrote {out_hdr}")


if __name__ == "__main__":
    main()
