"""Fit strictly minimum-phase 8-section biquad cascades to published reference curves
for the 5 flagship studio microphones and generate src/vocal/MicLockerCurves.h.
Asserts Test V1: max error <= 1.0 dB across 50 Hz .. 16 kHz for every model.
"""

from __future__ import annotations

import csv
from pathlib import Path
import numpy as np

from lab.biquad_fit import fit_minphase_biquads


def main() -> None:
    csv_path = Path("../../data/reference_curves/mic_locker_targets.csv")
    rows = []
    with csv_path.open("r", encoding="ascii") as f:
        reader = csv.DictReader(line for line in f if not line.startswith("#"))
        for row in reader:
            rows.append(row)

    freqs = np.array([float(r["freq_hz"]) for r in rows], dtype=np.float64)
    # Dense log-grid interpolation for clean continuous biquad fitting
    f_dense = np.geomspace(50.0, 16000.0, 128)

    specs = [
        ("SonyC800G",     "SonyC800G_db"),
        ("NeumannU87Ai",  "NeumannU87Ai_db"),
        ("Telefunken251", "Telefunken251E_db"),
        ("NeumannU47",    "NeumannU47_db"),
        ("ShureSm7b",     "ShureSm7b_db"),
    ]

    kind_map = {"peaking": 0, "lowshelf": 1, "highshelf": 2}
    lines = [
        "#pragma once",
        "",
        "// Auto-generated by tools/lab/lab/fit_mic_locker.py from data/reference_curves/mic_locker_targets.csv",
        "// Strictly minimum-phase RBJ biquad cascades validated within <= 1.0 dB across 50 Hz - 16 kHz (Test V1).",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace stoneridge::vocal {",
        "",
        "struct MicEqSection {",
        "    uint8_t kind;   // 0 = peaking, 1 = lowshelf, 2 = highshelf",
        "    float   freqHz;",
        "    float   q;",
        "    float   gainDb;",
        "};",
        "",
        "inline constexpr uint32_t kMicEqSections = 8u;",
        "inline constexpr uint32_t kMicModelCount = 5u;",
        "",
        "inline constexpr std::array<std::array<MicEqSection, kMicEqSections>, kMicModelCount> kMicLockerEqCurves = {{",
    ]

    for name, col in specs:
        y_pts = np.array([float(r[col]) for r in rows], dtype=np.float64)
        y_dense = np.interp(np.log2(f_dense), np.log2(freqs), y_pts)
        secs, rms_err, max_err = fit_minphase_biquads(f_dense, y_dense, num_peaking=6, fs=48000.0, gain_limit_db=8.0)
        # Enforce Test V1 <= 1.0 dB across 50 Hz - 16 kHz
        print(f"{name:14s}: RMS={rms_err:.3f} dB, Max={max_err:.3f} dB (50 Hz - 16 kHz)")
        if max_err > 1.0:
            raise RuntimeError(f"Test V1 failed for {name}: max_err={max_err:.3f} dB > 1.0 dB")

        lines.append(f"    // {name} (RMS={rms_err:.3f} dB, Max={max_err:.3f} dB)")
        lines.append("    {{")
        for s in secs:
            lines.append(f"        {{ {kind_map[s.kind]}u, {s.freq_hz:.2f}f, {s.q:.4f}f, {s.gain_db:.4f}f }},")
        lines.append("    }},")

    lines.extend([
        "}};",
        "",
        "} // namespace stoneridge::vocal",
        "",
    ])

    out_hdr = Path("../../src/vocal/MicLockerCurves.h")
    out_hdr.write_text("\n".join(lines), encoding="ascii")
    print(f"Wrote {out_hdr}")


if __name__ == "__main__":
    main()
